import os, struct, sys, wave

DIR = os.path.dirname(os.path.abspath(__file__))
SOUND_DIR = os.path.join(DIR, "声音")

def dump_pcm(wav_path):
    with wave.open(wav_path, "rb") as w:
        frames = w.readframes(w.getnframes())
        return struct.unpack(f"<{len(frames)//2}h", frames)

def main(out_path):
    done = dump_pcm(os.path.join(SOUND_DIR, "完成.wav"))
    wait = dump_pcm(os.path.join(SOUND_DIR, "等你.wav"))
    stuck = dump_pcm(os.path.join(SOUND_DIR, "卡住.wav"))

    with open(out_path, "w") as f:
        f.write("// Auto-generated by gen_audio.py - 16kHz mono 16-bit PCM\n#pragma once\n#include <stdint.h>\n\n")
        for name, data in [("audio_done", done), ("audio_wait", wait), ("audio_stuck", stuck)]:
            f.write(f"const int {name.upper()}_LEN = {len(data)};\n")
            f.write(f"const int16_t {name}[] = {{\n")
            for i in range(0, len(data), 16):
                f.write(",".join(str(x) for x in data[i:i+16]) + ",\n")
            f.write("};\n\n")
    print(f"Generated {out_path}: done={len(done)}, wait={len(wait)}, stuck={len(stuck)} samples")

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(DIR, "hid_status", "audio_data.h")
    main(out)
