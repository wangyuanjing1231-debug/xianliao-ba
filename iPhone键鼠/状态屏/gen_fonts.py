import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/opentype/noto/"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))

def gb2312():
    out = []
    for hi in list(range(0xA1, 0xAA)) + list(range(0xB0, 0xF8)):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes((hi, lo)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            out.append(ch)
    return "".join(out)

FULL = ASCII + gb2312() + "…"

FONTS = [
    ("F_BIG", "Bold", 23, FULL),
    ("F_SMALL", "Regular", 14, FULL),
    ("F_SMALLB", "Bold", 14, ASCII),
    ("F_HEAD", "Bold", 15, ASCII + "等你过时卡住在跑派单静音连接中"),
    ("F_EMPTY", "Medium", 18, "没有在跑的单"),
]

def build(name, weight, size, chars):
    f = ImageFont.truetype(FONT_DIR + f"NotoSansCJK-{weight}.ttc", size, index=2)
    ascent, descent = f.getmetrics()
    cps = sorted(set(ord(c) for c in chars))
    bitmap = bytearray()
    metrics = []
    for cp in cps:
        ch = chr(cp)
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(x1 - x0, 0), max(y1 - y0, 0)
        off = len(bitmap)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            px = list(im.getdata())
            for row in range(h):
                line = px[row * w:(row + 1) * w]
                for i in range(0, w, 2):
                    a = line[i] >> 4
                    b = (line[i + 1] >> 4) if i + 1 < w else 0
                    bitmap.append((a << 4) | b)
        metrics.append((off, w, h, x0, y0, adv))
    mid = (ascent - descent) // 2
    return cps, metrics, bitmap, mid

def main(out):
    with open(out, "w") as o:
        o.write("// generated by gen_fonts.py from Noto Sans SC\n#pragma once\n#include <stdint.h>\n")
        o.write("struct Glyph { uint32_t off; uint8_t w, h; int8_t dx, dy; uint8_t adv; };\n")
        o.write("struct Font { uint16_t n; int8_t mid; const uint32_t *cp; const Glyph *g; const uint8_t *bm; };\n")
        for name, weight, size, chars in FONTS:
            cps, metrics, bitmap, mid = build(name, weight, size, chars)
            o.write(f"static const uint32_t {name}_cp[] = {{{','.join(map(str, cps))}}};\n")
            o.write(f"static const Glyph {name}_g[] = {{" + ",".join(f"{{{a},{b},{c},{d},{e},{f}}}" for a, b, c, d, e, f in metrics) + "};\n")
            o.write(f"static const uint8_t {name}_bm[] = {{")
            for i in range(0, len(bitmap), 4096):
                o.write(",".join(str(x) for x in bitmap[i:i + 4096]) + ",\n")
            o.write("0};\n")
            o.write(f"static const Font {name} = {{{len(cps)},{mid},{name}_cp,{name}_g,{name}_bm}};\n")
            print(name, len(cps), "glyphs", len(bitmap), "bytes", file=sys.stderr)

main(sys.argv[1])
